#!/usr/bin/env python3
"""Build-time translation of the audited Electron stardust routines to 68000.
No interpreter, dispatch table, 6502 bytecode, or C is linked into the game.
D0/D1/D2 hold A/X/Y; D3 retains carry where needed across 68k instructions.
D4 retains a live N/Z result. Dead condition writes are removed by dataflow.
Source PIXEL is replaced by the QL raster adapter; arithmetic is untouched.
"""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
SYMS={n:i*19 for i,n in enumerate(['SX','SY','SZ','SXL','SYL','SZL'])}
SYMS['RAND']=114
for i,n in enumerate('P Q R S T T1 U XX YY X1 Y1 ZZ ALPHA BETA ALP1 ALP2 BET1 BET2 DELTA DELT4 RAT RAT2 VIEW SC'.split()):SYMS[n]=118+i*2
SIZE=168
code=[];labels={}
for raw in (ROOT/'tests/original-dust.asm').read_text().splitlines():
 t=raw.split('\\')[0].strip()
 if not t:continue
 if t.startswith('.'):labels[t[1:]]=len(code)
 else:
  op,*arg=t.split(None,1);code.append((op,arg[0] if arg else ''))
labels['MULTS-2']=labels['MULTS']-1;labels['LL28+4']=labels['LL28']+2
branches={'BEQ','BNE','BMI','BPL','BCS','BCC'}
setnz={'LDA','LDX','LDY','AND','ORA','EOR','ADC','SBC','CMP','CPX','CPY','LSR','ASL','ROR','ROL','TAX','TXA','TAY','TYA','DEX','DEY','INX','INY','DEC','INC','QLPIXEL'}
setc={'ADC','SBC','CMP','CPX','CPY','LSR','ASL','ROR','ROL','SEC','CLC','QLPIXEL'}
def target(i,arg):return i+2 if arg in ('P%+4','P%+5') else labels[arg]
# Liveness is deliberately conservative at subroutine boundaries.
live=[set() for _ in code];outs=[set() for _ in code]
for iteration in range(len(code)*2):
 changed=False
 for i in reversed(range(len(code))):
  op,arg=code[i];succ=[] if op=='RTS' else [target(i,arg)] if op=='JMP' else [i+1,target(i,arg)] if op in branches else [i+1]
  out=set().union(*(live[j] for j in succ if j<len(code)))
  if op in ('RTS','JSR'):out|={'C','NZ'}
  use=set()
  if op in ('ADC','SBC','ROR','ROL','BCS','BCC','JSR'):use.add('C')
  if op in ('BEQ','BNE','BMI','BPL'):use.add('NZ')
  kill=({'NZ'} if op in setnz else set())|({'C'} if op in setc else set())
  new=use|(out-kill)
  if new!=live[i] or out!=outs[i]:live[i]=new;outs[i]=out;changed=True
 if not changed:break

def operand(a):
 if a=='A':return 'd0'
 if a.startswith('#'):
  t=a[1:];v=int(t[1:],2 if t[0]=='%' else 16) if t[0] in '%&' else int(t);return '#'+str(v)
 base,*idx=a.split(',');bits=base.split('+');off=SYMS[bits[0]]+(int(bits[1]) if len(bits)>1 else 0)
 return str(off)+'(a2'+(',d'+{'X':'1','Y':'2'}[idx[0]]+'.w' if idx else '')+')'
lines=['; Generated by tools/dust_native.py from tests/original-dust.asm.','; Static native 68000 code. QL hardware boundary: dust_plot only.','.sect .text','.globl dust_original_init','.globl dust_original_step','.globl dust_original_flip','.globl dust_original_redraw']
for name,label in [('init','nWq'),('step','STARS'),('flip','FLIP'),('redraw','REDRAW')]:lines+=['dust_original_'+name+':',' bra dust_i'+str(labels[label])]
for i,(op,arg) in enumerate(code):
 lines+=['dust_i%d:'%i,' ; '+op+' '+arg];out=outs[i]
 def emit(*s):lines.extend(' '+x for x in s)
 def nz(reg):
  if 'NZ' in out:emit('move.b '+reg+',d4')
 def carry(cond='cs'):
  if 'C' in out:emit('s'+cond+' d3','and.b #1,d3')
 if op in ('LDA','LDX','LDY'):
  r='d'+str('AXY'.index(op[-1]));emit('move.b '+operand(arg)+','+r);nz(r)
 elif op in ('STA','STX','STY'):emit('move.b d'+str('AXY'.index(op[-1]))+','+operand(arg))
 elif op in ('AND','ORA','EOR'):
  x=operand(arg)
  if op=='EOR' and not x.startswith('#'):emit('move.b '+x+',d5');x='d5'
  emit({'AND':'and','ORA':'or','EOR':'eor'}[op]+'.b '+x+',d0');nz('d0')
 elif op in ('ADC','SBC'):
  emit('move.b '+operand(arg)+',d5')
  if op=='SBC':emit('eor.b #1,d3')
  emit('lsr.b #1,d3',('addx' if op=='ADC' else 'subx')+'.b d5,d0');carry('cs' if op=='ADC' else 'cc');nz('d0')
 elif op in ('CMP','CPX','CPY'):
  reg='d'+str('AXY'.index('A' if op=='CMP' else op[-1]));emit('move.b '+reg+',d5','sub.b '+operand(arg)+',d5');carry('cc');nz('d5')
 elif op in ('SEC','CLC'):
  if 'C' in out:emit('moveq #'+str(int(op=='SEC'))+',d3')
 elif op in ('LSR','ASL','ROR','ROL'):
  x=operand(arg)
  if op in ('ROR','ROL'):emit('lsr.b #1,d3')
  instr={'LSR':'lsr','ASL':'lsl','ROR':'roxr','ROL':'roxl'}[op]
  if x.startswith('d'):emit(instr+'.b #1,'+x);carry();nz(x)
  else:emit('move.b '+x+',d5',instr+'.b #1,d5');carry();emit('move.b d5,'+x);nz('d5')
 elif op in ('TAX','TXA','TAY','TYA'):
  a='d'+str('AXY'.index(op[1]));b='d'+str('AXY'.index(op[2]));emit('move.b '+a+','+b);nz(b)
 elif op in ('DEX','DEY','INX','INY','DEC','INC'):
  x=operand(arg) if op in ('DEC','INC') else 'd'+str('AXY'.index(op[-1]));emit(('subq' if op.startswith('DE') else 'addq')+'.b #1,'+x);nz(x)
 elif op in branches:
  emit('tst.b '+('d3' if op in ('BCS','BCC') else 'd4'),{'BCS':'bne','BCC':'beq'}.get(op,op.lower())+' dust_i'+str(target(i,arg)))
 elif op in ('JMP','JSR'):emit(('bra' if op=='JMP' else 'bsr')+' dust_i'+str(labels[arg]))
 elif op=='RTS':emit('rts')
 elif op=='QLPIXEL':emit('bsr dust_plot')
 else:raise ValueError((op,arg))
(ROOT/'src/dust_generated.s').write_text('\n'.join(lines)+'\n')
if __name__=='__main__':print('Native dust:',len(code),'source instructions;',len(lines),'native source lines;',SIZE,'state bytes')
