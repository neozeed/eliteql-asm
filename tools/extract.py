#!/usr/bin/env python3
"""Expand Electron blueprints into 68000 word records, retaining LOD metadata."""
import math,re,json,sys
from pathlib import Path
root=Path(__file__).resolve().parents[1]
s=Path(sys.argv[1]).read_text()
names=re.findall(r'^\.SHIP_([A-Z_0-9]+)_VERTICES\s*$',s,re.M)
models=[]
for name in names:
 head=s.split('\n.SHIP_'+name+'\n',1)[1].split('\n.SHIP_',1)[0]
 def field(label):
  line=next(l for l in head.splitlines() if label in l)
  expr=line.split('\\')[0].split(None,1)[1].strip()
  return math.prod(int(x.strip()) for x in expr.split("*"))
 m={'name':name,'type':len(models)+1 if len(models)<5 else len(models)+2,'energy':field('Max. energy'),'area':field('Targetable area'),'max_speed':field('Max. speed'),'normal_shift':field('Normals are scaled'),'distance':field('Visibility distance'),'max_lines':(field('Max. edge count')-1)//4}
 for section,macro in [('VERTICES','VERTEX'),('EDGES','EDGE'),('FACES','FACE')]:
  part=s.split('.SHIP_'+name+'_'+section,1)[1].split('\n.SHIP_',1)[0]
  m[section.lower()]=[[int(v.strip()) for v in z.group(1).split(',')] for line in part.splitlines() if (z:=re.match(r'\s*'+macro+r'\s+([^\\]+)',line))]
 models.append(m)
matrices=[]
for a in range(256):
 yaw=a*math.pi/128; pitch=math.sin(yaw)*math.pi/6;roll=2*yaw
 cy,sy=math.cos(yaw),math.sin(yaw);cp,sp=math.cos(pitch),math.sin(pitch);cr,sr=math.cos(roll),math.sin(roll)
 cols=[]
 for x,y,z in [(1,0,0),(0,1,0),(0,0,1)]:
  x,z=x*cy+z*sy,z*cy-x*sy
  y,z=y*cp-z*sp,z*cp+y*sp
  x,y=x*cr-y*sr,y*cr+x*sr
  cols.append([round(x*256),round(y*256),round(z*256)])
 matrices.append([cols[j][i] for i in range(3) for j in range(3)])
lines=['; Expanded original Electron geometry; generated by tools/extract.py.','.sect .text','.sect .rom','.sect .data','.sect .bss','.sect .rom','.align 2','.globl _models','.globl _orientations','_models:']
lines+=['.data4 model_'+str(i) for i in range(len(models))]
for i,m in enumerate(models):
 lines+=['model_'+str(i)+':','.data2 '+','.join(map(str,[len(m['vertices']),len(m['edges']),len(m['faces']),m['distance'],m['max_lines']])) ,'.data4 vertices_'+str(i)+',edges_'+str(i)+',faces_'+str(i),'.data2 '+','.join(map(str,[m['max_speed'],m['energy'],m['area'],m['type']])),'vertices_'+str(i)+':']
 for v in m['vertices']:
  lines+=['.data2 '+','.join(map(str,v[:3]+[v[7]])),'.data1 '+','.join(map(str,v[3:7]))]
 lines+=['edges_'+str(i)+':']
 for v in m['edges']:lines+=['.data1 '+','.join(map(str,v+[0]))]
 lines+=['faces_'+str(i)+':']
 for v in m['faces']:lines+=['.data2 '+','.join(map(str,v)),'.data4 '+str(sum(c*c for c in v[:3])>>m['normal_shift'])]
lines+=['_orientations:']
for v in matrices:lines+=['.data2 '+','.join(map(str,v))]
(root/'src/models.s').write_text('\n'.join(lines)+'\n')
(root/'tests/models.json').write_text(json.dumps({'models':models,'matrices':matrices},indent=2)+'\n')
print('Extracted',len(models),'models; original vertex-face/edge/face LOD and line caps retained')
